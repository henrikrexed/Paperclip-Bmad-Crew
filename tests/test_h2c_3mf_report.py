def test_optional_real_fixture_dir_is_gated() -> None:
    fixture_dir = os.environ.get("H2C_3MF_FIXTURE_DIR")
    if not fixture_dir:
        pytest.skip("H2C_3MF_FIXTURE_DIR not set; real H2C validation gated on Board-provided fixtures/profiles/binaries")
    paths = sorted(Path(fixture_dir).glob("*.3mf")) + sorted(Path(fixture_dir).glob("*.gcode.3mf"))
    assert paths, "H2C_3MF_FIXTURE_DIR must contain at least one 3MF fixture"
    for path in paths:
        report = analyze_path(path)
        assert report["schema_name"] == "h2c-3mf-report.v1"
