def test_slicer_command_builder_and_fake_runner_success(tmp_path: Path) -> None:
    input_path = _write_3mf(tmp_path / "raw.3mf", {"3D/3dmodel.model": "<model />"})
    output_path = tmp_path / "work" / "raw.gcode.3mf"
    machine = tmp_path / "h2c_machine.json"
    process = tmp_path / "process.json"
    filament = tmp_path / "pla.json"
    for path in [machine, process, filament]:
        path.write_text("{}", encoding="utf-8")
    fake_slicer = tmp_path / "fake-slicer"
    fake_slicer.write_text("#!/bin/sh\nexit 0\n", encoding="utf-8")
    fake_slicer.chmod(fake_slicer.stat().st_mode | stat.S_IXUSR)
    config = ProfileConfig(machine_profile=machine, process_profile=process, filament_profiles=[filament], bed_type="Textured PEI Plate")

    def fake_runner(command: list[str], cwd: Path, timeout: int | None):
        output_path.parent.mkdir(parents=True, exist_ok=True)
        _write_3mf(output_path, {"Metadata/plate_1.gcode": _gcode(), "Metadata/slice_info.config": _slice_info([(1, [{"id": 1, "type": "PLA", "color": "000000", "used_m": 1, "used_g": 12.34}])])})
        return subprocess.CompletedProcess(command, 0, "", "")

    request = SlicerRequest(input_path, output_path, "bambu-studio", fake_slicer, config, tmp_path / "work")
    result = run_slicer(request, runner=fake_runner)

    assert result.ok is True
    assert result.output_path == output_path
    assert result.profiles is not None
    assert result.profiles["machine"]["basename"] == "h2c_machine.json"
    assert "--load-settings" in result.command
    assert "--load-filaments" in result.command


