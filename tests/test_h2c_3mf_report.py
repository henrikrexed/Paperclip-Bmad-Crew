def test_cli_emits_valid_json_for_multiple_inputs_jsonl(tmp_path: Path) -> None:
    good = _write_3mf(tmp_path / "good.gcode.3mf", {"Metadata/plate_1.gcode": _gcode(), "Metadata/slice_info.config": _slice_info([(1, [{"id": 1, "type": "PLA", "color": "000", "used_m": 1, "used_g": 12.34}])])})
    raw = _write_3mf(tmp_path / "raw.3mf", {"3D/3dmodel.model": "<model />"})

    project_root = Path(__file__).resolve().parents[1]
    env = {**os.environ, "PYTHONPATH": str(project_root / "src")}
    result = subprocess.run(
        [sys.executable, "-m", "h2c_3mf_report", "--jsonl", str(good), str(raw)],
        cwd=project_root,
        env=env,
        text=True,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        check=False,
    )

    assert result.returncode == 2
    rows = [json.loads(line) for line in result.stdout.splitlines()]
    assert [row["file"] for row in rows] == [good.name, raw.name]
    assert rows[0]["status"] == "ok"
    assert rows[1]["errors"][0]["code"] == "UNSLICED_FILE"


