    assert report["totals"]["filament_used_g_from_slice_info"] == 59.63
    assert report["totals"]["filament_used_m_from_slice_info"] == 18.72
    assert report["totals"]["filament_weight_g_from_gcode"] == 59.63
    assert report["totals"]["print_time_seconds"] == 9102
    plate = report["plates"][0]
    assert plate["colors"] == ["#000000", "#FFFFFF"]
    assert plate["filament_types"] == ["PLA"]
    assert plate["gcode"]["unknown_fields"] == {"custom slicer field": "keep-me"}
    assert plate["filaments"][0]["raw_attributes"] == {"custom_attr": "preserved"}
    assert report["source_files"] == [{"path": "models/cube.stl", "name": "cube.stl"}]


